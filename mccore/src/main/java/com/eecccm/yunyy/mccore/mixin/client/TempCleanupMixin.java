package com.eecccm.yunyy.mccore.mixin.client;

import com.eecccm.yunyy.mccore.client.GainDevice;
import com.mojang.blaze3d.audio.Library;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** 拦截音频库清理：释放模组持有的音源句柄。 */
@Mixin({Library.class})
public abstract class TempCleanupMixin {
   @Inject(
      method = {"cleanup"},
      at = {@At("HEAD")}
   )
   private void yunyy$releaseMusicHandles(CallbackInfo callback) {
      GainDevice.beforeLibraryCleanup((Library)(Object)this);
   }
}
